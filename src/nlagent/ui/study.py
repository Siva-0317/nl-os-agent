# 4. Study Session Controller
# -----------------------------------------------------------------------------

class StudySession:
    """Controls the active experiment flow for a single participant."""

    def __init__(
        self,
        participant: StudyParticipant,
        tasks: Sequence[StudyTask] | None = None,
        logger_instance: StudyLogger | None = None,
    ) -> None:
        self.participant = participant
        self.tasks: list[StudyTask] = list(tasks if tasks is not None else DEFAULT_STUDY_TASKS)
        self.logger = logger_instance or StudyLogger()
        self.current_task_idx = 0
        self.session_records: list[StudyTrialRecord] = []

        # Timers
        self._trial_start_time = 0.0
        self._preview_inspect_time = 0.0

    def start_trial(self) -> None:
        """Mark start of a new trial presentation."""
        self._trial_start_time = time.perf_counter()
        self._preview_inspect_time = self._trial_start_time

    def mark_preview_inspected(self) -> None:
        """Record when user moves from inspecting preview to answering comprehension."""
        self._preview_inspect_time = time.perf_counter()

    def current_task(self) -> StudyTask | None:
        """Get currently active task."""
        if self.current_task_idx < len(self.tasks):
            return self.tasks[self.current_task_idx]
        return None

    def is_completed(self) -> bool:
        """Check if all tasks in battery have been completed."""
        return self.current_task_idx >= len(self.tasks)

    def record_decision(
        self,
        chosen_option_idx: int,
        approval_decision: str,  # 'approve' | 'cancel'
    ) -> StudyTrialRecord:
        """Process user answers and record telemetry for current task."""
        task = self.current_task()
        if not task:
            raise RuntimeError("No active study task to record.")

        now = time.perf_counter()
        inspection_duration_ms = max(1.0, (self._preview_inspect_time - self._trial_start_time) * 1000.0)
        decision_duration_ms = max(1.0, (now - self._preview_inspect_time) * 1000.0)
        total_duration_ms = max(2.0, (now - self._trial_start_time) * 1000.0)

        # Evaluation metrics
        is_comprehension_correct = (chosen_option_idx == task.correct_option_idx)
        is_safe_decision = (
            (approval_decision == "approve" and not task.is_harmful)
            or (approval_decision == "cancel" and task.is_harmful)
        )
        is_accidental_approval = bool(approval_decision == "approve" and task.is_harmful)

        # Content shown based on condition
        if self.participant.condition == DisplayCondition.PLAIN_PREVIEW:
            preview_displayed = task.plain_preview
        else:
            preview_displayed = task.command

        chosen_text = task.options[chosen_option_idx] if 0 <= chosen_option_idx < len(task.options) else "Invalid Option"

        rec = StudyTrialRecord(
            run_id=secrets.token_hex(6),
            participant_id=self.participant.participant_id,
            task_id=task.task_id,
            condition=self.participant.condition.value,
            request=task.request,
            command=task.command,
            preview_displayed=preview_displayed,
            is_harmful=task.is_harmful,
            expected_decision=task.expected_decision,
            approval_decision=approval_decision,
            is_safe_decision=is_safe_decision,
            is_accidental_approval=is_accidental_approval,
            comprehension_answer=chosen_text,
            is_comprehension_correct=is_comprehension_correct,
            inspection_duration_ms=round(inspection_duration_ms, 2),
            decision_duration_ms=round(decision_duration_ms, 2),
            total_duration_ms=round(total_duration_ms, 2),
        )

        # Save to disk
        self.logger.log_trial(rec)
        self.session_records.append(rec)
        self.current_task_idx += 1

        return rec

    def summary_stats(self) -> dict[str, Any]:
        """Compute aggregate evaluation metrics for the participant session."""
        if not self.session_records:
            return {
                "total_trials": 0,
                "comprehension_accuracy": 0.0,
                "safe_decision_rate": 0.0,
                "accidental_approval_rate": 0.0,
                "mean_inspection_ms": 0.0,
                "mean_total_ms": 0.0,
            }

        n = len(self.session_records)
        correct_comp = sum(1 for r in self.session_records if r.is_comprehension_correct)
        safe_dec = sum(1 for r in self.session_records if r.is_safe_decision)

        harmful_trials = [r for r in self.session_records if r.is_harmful]
        accidental_approvals = sum(1 for r in harmful_trials if r.is_accidental_approval)
        accidental_rate = (accidental_approvals / len(harmful_trials)) if harmful_trials else 0.0

        mean_inspect = sum(r.inspection_duration_ms for r in self.session_records) / n
        mean_total = sum(r.total_duration_ms for r in self.session_records) / n

        return {
            "total_trials": n,
            "condition": self.participant.condition.value,
            "comprehension_accuracy": round((correct_comp / n) * 100.0, 1),
            "safe_decision_rate": round((safe_dec / n) * 100.0, 1),
            "accidental_approval_rate": round(accidental_rate * 100.0, 1),
            "mean_inspection_ms": round(mean_inspect, 1),
            "mean_total_ms": round(mean_total, 1),
        }
