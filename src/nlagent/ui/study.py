# -----------------------------------------------------------------------------
# 3. Local Air-Gapped Study Logger (Zero-Network)
# -----------------------------------------------------------------------------

class StudyLogger:
    """Thread-safe, air-gapped local JSONL logger for usability study trials."""

    def __init__(self, output_path: str | Path | None = None) -> None:
        if output_path:
            self.output_path = Path(output_path).resolve()
        else:
            repo_root = Path(__file__).resolve().parent.parent.parent.parent
            self.output_path = repo_root / "results" / "study_trials.jsonl"

        self.output_path.parent.mkdir(parents=True, exist_ok=True)
        self._lock = threading.Lock()

    def log_trial(self, record: StudyTrialRecord) -> None:
        """Atomically append a trial record to the local JSONL file."""
        data_line = json.dumps(record.to_dict(), ensure_ascii=False) + "\n"
        with self._lock:
            with open(self.output_path, "a", encoding="utf-8") as f:
                f.write(data_line)
                f.flush()

    def load_records(self, participant_id: str | None = None) -> list[StudyTrialRecord]:
        """Load logged records from disk."""
        if not self.output_path.exists():
            return []

        records: list[StudyTrialRecord] = []
        with self._lock:
            with open(self.output_path, "r", encoding="utf-8") as f:
                for line in f:
                    line_str = line.strip()
                    if not line_str:
                        continue
                    try:
                        raw = json.loads(line_str)
                        if participant_id and raw.get("participant_id") != participant_id:
                            continue
                        rec = StudyTrialRecord(**raw)
                        records.append(rec)
                    except Exception as e:
                        logger.warning("Failed to parse trial log line: %s", e)
        return records


