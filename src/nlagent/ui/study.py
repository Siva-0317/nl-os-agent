class DisplayCondition(str, enum.Enum):
    """Display condition for the usability study pilot."""
    PLAIN_PREVIEW = "plain_preview"  # Consequence summary from AST Renderer
    RAW_COMMAND = "raw_command"      # Raw shell command string only


@dataclass
class StudyParticipant:
    """Anonymous participant record."""
    participant_id: str
    condition: DisplayCondition
    consented: bool = False
    consented_at: str = ""
    created_at: str = field(default_factory=lambda: datetime.datetime.now(datetime.timezone.utc).isoformat())

    @classmethod
    def generate(cls, condition: DisplayCondition | None = None) -> StudyParticipant:
        """Create a new participant with a cryptographic pseudorandom anonymous ID."""
        pid = f"P-{secrets.token_hex(3).upper()}"
        if condition is None:
            # Deterministic/random assignment between conditions
            condition = secrets.choice(list(DisplayCondition))
        return cls(participant_id=pid, condition=condition)


@dataclass
class StudyTask:
    """Pre-registered task presentation for human-factors trials."""
    task_id: str
    title: str
    request: str
    command: str
    plain_preview: str
    expected_tier: str  # 'read_only' | 'state_modifying' | 'destructive' | 'privileged' | 'ambiguous'
    is_harmful: bool
    expected_decision: str  # 'approve' | 'cancel'
    comprehension_question: str
    options: list[str]
    correct_option_idx: int
    quarantine_eligible: bool = True
    bytes_affected: int = 0


@dataclass
class StudyTrialRecord:
    """Structured record for an individual study trial event."""
    run_id: str
    participant_id: str
    task_id: str
    condition: str
    request: str
    command: str
    preview_displayed: str
    is_harmful: bool
    expected_decision: str
    approval_decision: str  # 'approve' | 'cancel'
    is_safe_decision: bool
    is_accidental_approval: bool
    comprehension_answer: str
    is_comprehension_correct: bool
    inspection_duration_ms: float
    decision_duration_ms: float
    total_duration_ms: float
    timestamp: str = field(default_factory=lambda: datetime.datetime.now(datetime.timezone.utc).isoformat())

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


